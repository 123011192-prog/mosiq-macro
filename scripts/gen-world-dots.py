def inside(lon: float, lat: float) -> bool:
    """射线法判断点是否在任一多边形内（偶奇规则，逐多边形）。"""
    for poly in POLYS:
        hit = False
        n = len(poly)
        for i in range(n):
            x1, y1 = poly[i]
            x2, y2 = poly[(i + 1) % n]
            if (y1 > lat) != (y2 > lat):
                xint = (x2 - x1) * (lat - y1) / (y2 - y1) + x1
                if lon < xint:
                    hit = not hit
        if hit:
            return True
    return False


def main() -> None:
    rows = []
    for j in range(H):
        lat = 90 - (j + 0.5) * 180 / H
        line = ""
        for i in range(W):
            lon = -180 + (i + 0.5) * 360 / W
            line += "#" if inside(lon, lat) else "."
        rows.append(line)

    land = sum(r.count("#") for r in rows)
    print(f"grid {W}x{H}, land dots: {land}")
    for r in rows:
        print(r)

    # 预览 PNG
    from PIL import Image, ImageDraw

    cell = 12
    img = Image.new("RGB", (W * cell, H * cell), "#ffffff")
    d = ImageDraw.Draw(img)
    for j, r in enumerate(rows):
        for i, c in enumerate(r):
            if c == "#":
                cx, cy = i * cell + cell // 2, j * cell + cell // 2
                d.ellipse([cx - 4, cy - 4, cx + 4, cy + 4], fill="#8a99ad")
    out_png = Path(__file__).with_name("world-dots-preview.png")
    img.save(out_png)
    print("preview:", out_png)

    # TS 数据文件
    ts = Path(__file__).parent.parent / "src" / "data" / "world-dots.ts"
    ts.parent.mkdir(parents=True, exist_ok=True)
    body = "\n".join(f"  '{r}'," for r in rows)
    ts.write_text(
        "/** 抽象点阵世界地图陆地点阵（等距圆柱投影，# = 陆地）。\n"
        " * 由 scripts/gen-world-dots.py 生成；抽象风格，无国界、无地名。 */\n"
        f"export const WORLD_GRID_W = {W}\n"
        f"export const WORLD_GRID_H = {H}\n"
        "export const WORLD_DOTS: string[] = [\n" + body + "\n]\n",
        encoding="utf-8",
    )
    print("ts:", ts)


if __name__ == "__main__":
    main()
